"""Stage 2 gate: a strict review of each draft by llm.REVIEW_MODEL (default Kimi K3 over OpenRouter).

The reviewer applies SKILL.md (stage 2 rules; package items it cannot see yet are "deferred") and every document in
guidelines/, and estimates how often Astra would pass the finished task. A draft passes when no required rule fails
and the estimated Astra pass probability per attempt is at most the target (domain.json "astra_target", default
0.5, the "medium" band). refine.py runs this review in a loop with revisions; judge_drafts gives a single verdict.
Calibrate before trusting it: `uv run judge.py --calibrate` on seeds labelled good/bad.
"""
import argparse
import json
from pathlib import Path
from typing import List, Literal

from pydantic import BaseModel, Field

import archive
import llm
from domain import HERE, REPO, Domain, guidelines


class Criterion(BaseModel):
    rule: str = Field(description='rule name as SKILL.md or the guidelines word it')
    required: bool
    verdict: Literal['pass', 'fail', 'unclear', 'deferred']
    evidence: str = Field(description='short quote, number or what is missing')
    fix: str = Field(description='the concrete change; empty when it passes')


class AstraEstimate(BaseModel):
    p_pass_per_attempt: float = Field(description='probability, 0 to 1, that one Astra attempt passes every row')
    easiest_route: str = Field(description='the most likely way a strong agent passes, step by step')
    where_it_fails: str = Field(description='the specific row and moment where Astra most likely fails, and why')
    confidence: Literal['low', 'medium', 'high']


class Review(BaseModel):
    verdict: Literal['ready', 'fix first', 'not a forge task']
    reasons: List[str] = Field(description='the 2-4 reasons that decide the verdict')
    criteria: List[Criterion]
    astra: AstraEstimate
    fixes: List[str] = Field(description='at most 10, most important first, each naming the rule it serves')


SYSTEM = """You are the final gate for engineering design tasks in the FAIR Forge benchmark, and you are strict. A
draft you pass goes to a subject-matter engineer for days of work, and a weak task that reaches the client costs far
more than a rejection. Default to "fail" or "unclear" whenever the draft does not settle a rule; never give the
benefit of the doubt. Check numbers yourself: recompute constants, units, time constants, simulation costs and
margins from the draft's own values, and treat any value you cannot reproduce as a defect. Judge what is written,
not what the author says it intended.

The benchmark's review skill (apply its stage 2 rules):
<skill>
{skill}
</skill>

The guidelines every task follows:
<guidelines>
{guidelines}
</guidelines>"""

PROMPT = """Review this draft task.

It is a draft: the brief, handbook and generated input files are final text; the grader, reference solution and
package are a plan an engineer builds next. Mark package items you cannot see yet (reference solution, canary,
task.toml, self-tests) "deferred"; judge everything else now, including whether the plan can be built and run.

The task targets this model limitation, observed in real trials of {models}:
<limitation>
{limitation}
</limitation>

{task}

Give one criterion per rule: every SKILL.md stage 2 rule by its name, plus these required ones from the guidelines:
"no public solution", "survives own checks", "no ungraded preference", "brief says what, not how", "binding
limits", "artifacts exist" (rule 9: every file the brief or plan relies on is available or generated by the draft;
no repair premise on a baseline that does not exist), and "targets limitation" (an agent showing the limitation
fails at least one requirement and no route around it passes every row).

Then estimate Astra: the probability that a single attempt by a strong frontier agent (Astra) passes every row of the
finished task, with the 2 h, 400-turn budget, internet on, no handbook. Work out the easiest route a strong agent
would take before you estimate, and say where it would fail. Base it on the engineering, not on the author's claims.
For reference, Astra passed {astra_evidence}."""


def draft_text(draft):
    sec = lambda title, body: f'## {title}\n{body}\n' if body else ''
    rows = '\n'.join(f"- {r['rid']}: {r['metric']} | {r['condition']} | at {r['location']} | {r['limit']}"
                     for r in draft['requirements'])
    checks = '\n'.join(f"- {c['cid']} covers {', '.join(c['covers'])}: {c['method']}; reports {c['reports']}; "
                       f"tolerance: {c['tolerance']}" + (f"; held out: {c['held_out']}" if c['held_out'] else '')
                       for c in draft['grader_checks'])
    assets = '\n'.join(f"- {a['path']} [{a.get('status', 'unspecified')}]: {a['purpose']}"
                       + (f"\n```\n{a['content']}\n```" if a.get('content') else '') for a in draft['provided_assets'])
    return '\n'.join([
        f"# {draft['title']}  (form: {draft['task_form']}; freedom: {draft['design_freedom']}; author's difficulty "
        f"target: {draft['difficulty_target']})",
        sec('Brief (model-visible: instruction.md)', draft['instruction_md']),
        sec('Handbook (model-visible in handbook mode only)', draft['handbook_md']),
        sec('Parts catalogue (handbook mode only)', draft['parts_catalogue_md']),
        sec('Input assets (model-visible; status: available in the image, generated by this draft, or prerequisite)',
            assets),
        sec('Requirements as the author tabulated them', rows),
        sec('Output files', '\n'.join(f"- {o['path']} ({o['format']}): {o['contents']}" for o in draft['outputs'])),
        sec('Grader plan (evaluator-only)', checks),
        sec('Tools', ', '.join(draft['tools'])),
        sec('Distinct valid designs the author expects (evaluator-only)',
            '\n'.join(f'- {x}' for x in draft['distinct_valid_designs'])),
        sec('Budget fit (author)', draft['budget_fit']),
        sec('Public designs the author checked (evaluator-only)', '\n'.join(
            f"- {x['name']} ({x['source']}): fails {x['fails']}" for x in draft.get('public_designs', []))),
        sec("Why the limitation survives the solver's own checks (author)", draft.get('mechanism_survival', '')),
        sec('Catching rows (author)', ', '.join(draft.get('catching_rows', []))),
        sec('Reference outline (evaluator-only)', draft['reference_outline']),
        sec('Open risks (author)', '\n'.join(f'- {r}' for r in draft['open_risks']))])


def astra_evidence(domain):
    """What the archive knows about Astra on real tasks, as a calibration anchor for the estimate."""
    arc = archive.load(domain)
    rows = [f"{e['pass_rate']['passed']}/{e['pass_rate']['trials']} on {e['id']} ({e['summary']})"
            for e in arc['entries'] if e.get('pass_rate')]
    return '; '.join(rows) or 'no recorded trials yet'


def passes(review, target):
    hard_fail = [c.rule for c in review.criteria if c.required and c.verdict in ('fail', 'unclear')]
    p = min(max(review.astra.p_pass_per_attempt, 0.0), 1.0)
    return review.verdict == 'ready' and not hard_fail and p <= target, hard_fail


def review(draft, limitation, domain, skill_text, models=()):
    lim = {k: limitation[k] for k in ('id', 'name', 'mechanism', 'how_to_elicit', 'how_to_grade', 'evidence')} \
        if limitation else {}
    system = SYSTEM.format(skill=skill_text or '(no SKILL.md: apply the guidelines only)', guidelines=guidelines())
    prompt = PROMPT.format(models=', '.join(models) or 'the target model',
                           limitation=json.dumps(lim, indent=1, ensure_ascii=False),
                           task=draft_text(draft), astra_evidence=astra_evidence(domain))
    return llm.review_parse(system, prompt, Review)


def verdict_record(rv, target, rounds=None):
    """skill_check.json: what package.py and run.py read, plus the full review."""
    ok, hard_fail = passes(rv, target)
    return {'pass': ok, 'checklist': f'{llm.REVIEW_MODEL}: SKILL.md + guidelines/ + Astra <= {target}',
            'verdict': rv.verdict, 'reasons': rv.reasons, 'failed_rules': hard_fail,
            'astra': rv.astra.model_dump(), 'top_fixes': rv.fixes, 'rounds': rounds,
            'criteria': [{'name': c.rule, 'required': c.required, 'verdict': c.verdict, 'evidence': c.evidence,
                          'fix': c.fix} for c in rv.criteria]}


def judge_drafts(draft_dirs, skill_file=None):
    """One review per draft, no revisions (refine.py adds the loop)."""
    skill = Path(skill_file).read_text() if skill_file and Path(skill_file).exists() else None
    results = {}
    for d in draft_dirs:
        meta = json.loads((d / 'draft.json').read_text())
        domain = Domain(meta['domain'])
        target = domain.get('astra_target', 0.5)
        rv = review(meta['draft'], meta.get('limitation'), domain, skill, meta.get('catalogue_models', ()))
        v = verdict_record(rv, target)
        (d / 'skill_check.json').write_text(json.dumps(v, indent=1, ensure_ascii=False))
        if meta.get('archive_id'):  # later drafts see why this one failed
            archive.update(domain, meta['archive_id'], status='judge-pass' if v['pass'] else 'judge-fail',
                           notes=[f"failed: {', '.join(v['failed_rules'])}; Astra p={rv.astra.p_pass_per_attempt:.2f}"]
                           + rv.fixes[:3])
        print(f"  {'PASS' if v['pass'] else 'FAIL'} {d.name}: {rv.verdict}, Astra p={rv.astra.p_pass_per_attempt:.2f}"
              + (f"  failed: {', '.join(v['failed_rules'])}" if v['failed_rules'] else ''), flush=True)
        results[d.name] = v
    return results


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--skill', type=Path, default=HERE / 'SKILL.md')
    ap.add_argument('--domain', default='electrical')
    ap.add_argument('--calibrate', action='store_true', help='review the labelled seeds and report agreement')
    a = ap.parse_args()
    if a.calibrate:
        dom = Domain(a.domain)
        skill = a.skill.read_text() if a.skill.exists() else None
        system = SYSTEM.format(skill=skill or '(no SKILL.md: apply the guidelines only)', guidelines=guidelines())
        seeds = [s for s in json.loads(dom.seeds_file.read_text())['seeds'] if s['quality'] in ('good', 'bad')]
        agree = 0
        for s in seeds:
            rv = llm.review_parse(system, PROMPT.format(models='the target model', limitation='{}',
                                                        task=(REPO / s['statement']).read_text(),
                                                        astra_evidence=astra_evidence(dom)), Review)
            ok = passes(rv, dom.get('astra_target', 0.5))[0] == (s['quality'] == 'good')
            agree += ok
            print(f"  {s['id']}: labelled {s['quality']}, review {rv.verdict}{'' if ok else '  <-- disagrees'}")
        print(f'agreement {agree}/{len(seeds)}' if seeds else 'label seeds good/bad in seeds.json first')
