"""Stage 3: package a draft as a Terminal-Bench 4.0 (Harbor) task folder + zip in the CF-1.0 layout
(kforge/docs/CANONICAL_FORMAT.md section 7; reference: tasks/lp1-broadband-match).

  instruction.md            the brief (model-visible)
  task.toml                 name = folder name, version, binary reward, artifacts /app/output, rationale fields,
                            agent network public, verifier in its own container with no network
  README.md                 version and changelog
  environment/              Dockerfile FROM the domain image; starter/ (port connectors) and input_assets/ (generated
                            inputs) copied into /app. Never the handbook.
  handbook/                 handbook.md (+ parts_catalogue.md): outside environment/, removable (client feedback)
  tests/                    the kforge grader: requirements.yaml (+ catalog/, models/), test.sh (grade -> checks.json
                            + reward.txt -> CTRF per check), Dockerfile FROM the grader image with kforge vendored
  solution/                 solve.sh that fails until the SME adds the golden design; REFERENCE_OUTLINE.md
  sme/                      evaluator_design/ (the evaluator's passing design, if any; not a golden solution),
                            evaluation.json, skill_check.json
  SME_NOTES.md              status, limitation, Astra estimate, build results, what to do next
Every file carries the FAIR Forge canary. Drafts without a validated kit are packaged with a smoke-only tests/.
"""
import json
import shutil
import time
from pathlib import Path

from domain import CANARY, REPO, Domain

TASK_TOML = '''# {canary}
schema_version = "1.4"
artifacts = ["/app/output"]

[task]
name = {name}
version = "0.1.0"
description = {description}
keywords = {keywords}

[metadata]
reward_type = "binary"
category = "Hardware"
subcategory = {subcategory}
draft = true
generator = "taskgen_poc"
targets_limitation = {limitation}
difficulty_target = {difficulty}
difficulty_explanation = {difficulty_reason}
solution_explanation = {reference}
verification_explanation = {grader}
astra_estimate = {astra}

[verifier]
timeout_sec = 3600.0
environment_mode = "separate"

[verifier.environment]
network_mode = "no-network"
build_timeout_sec = 1800.0
os = "linux"
cpus = 4
memory_mb = 8192

[agent]
timeout_sec = 7200.0

[environment]
network_mode = "public"
build_timeout_sec = 1800.0
os = "linux"
cpus = 4
memory_mb = 8192
'''

ENV_DOCKERFILE = '''# {canary}
# Agent environment: KiCad 10.0.6 + ngspice-47 + Python. Starter project and task inputs are copied into /app.
# The handbook is not part of the image (handbook/ next to this folder is supplied separately in handbook mode).
FROM {image}
USER root
COPY starter /app/starter
COPY input_assets /app/input_assets
RUN mkdir -p /app/output && chmod 777 /app/output
WORKDIR /app
'''

TESTS_DOCKERFILE = '''# {canary}
FROM {image}
USER root
COPY kforge /opt/kforge/kforge
ENV PYTHONPATH=/opt/kforge
COPY . /tests/
RUN rm -rf /tests/kforge && chmod 755 /tests/test.sh && mkdir -p /app/output
'''

TEST_SH = '''#!/bin/bash
# {canary}
# kforge verifier: grade -> checks.json + reward.txt (withheld on grader_error) -> CTRF per check.
mkdir -p /logs/verifier && chmod 700 /logs/verifier
python /tests/run_kforge.py grade --spec /tests/requirements.yaml --deliverable /app/output --out /logs/verifier
gexit=$?
KFORGE_CHECKS=/logs/verifier/checks.json python -m pytest -q -p no:cacheprovider \\
    /opt/kforge/kforge/report/ctrf_tests.py --ctrf /logs/verifier/ctrf.json > /logs/verifier/pytest.txt 2>&1
exit $gexit
'''

SMOKE_SH = '''#!/bin/bash
# {canary}
# DRAFT smoke grader: no validated kforge spec yet (see SME_NOTES.md). Reward 0 until the real grader exists.
mkdir -p /logs/verifier
test -f /app/output/design/design.kicad_sch && echo "deliverable present" || echo "deliverable missing"
echo 0 > /logs/verifier/reward.txt
exit 1
'''

README = '''# {title}

{canary}

{one_line}

Version: 0.1.0 (draft)

## Changelog

- 0.1.0 ({date}): draft generated by taskgen_poc, targeting limitation `{limitation}`. {status}
'''


def toml_str(s):
    return json.dumps(str(s), ensure_ascii=False)  # a JSON string is a valid TOML basic string


def canary_md(text):
    return f'{text.rstrip()}\n\n<!-- {CANARY} -->\n'


def canary_yaml(text):
    return f'# {CANARY}\n{text}' if CANARY not in text else text


def sme_notes(meta, check, ev):
    draft, lim = meta['draft'], meta.get('limitation') or {}
    ready = meta.get('ready')
    inf = (ev or {}).get('informed') or {}
    a = (ev or {}).get('assessment') or {}
    L = [f"# {draft['title']} (DRAFT)", '', draft['one_line'], '', '## Status',
         f"- {'READY DRAFT' if ready else 'NOT READY'}: " + (
             'The evaluator built a passing design with the real grader. Ready for engineering review; difficulty remains uncalibrated. '
             'Next: run it on Astra (8 attempts). If Astra fails, write the golden solution '
             '(sme/evaluator_design is a starting point, not a golden). If Astra passes, tighten the binding checks '
             'below and re-run.' if ready else 'see the fixes below before an engineer spends time on it.'),
         f"- Subdomain: {meta.get('subdomain')}; cell limitation: `{lim.get('id')}`; generated in "
         f"{(meta.get('provenance') or {}).get('mode', '?')} mode",
         f"- Static review: {check.get('verdict') if check else 'not run'}"
         + (f"; failed rules: {', '.join(check['failed_rules'])}" if check and check.get('failed_rules') else '')]
    if check:
        L.append(f"- Astra estimate: p={check['astra']['p_pass_per_attempt']} per attempt "
                 f"({check['astra'].get('source', 'static review')})")
    if ev:
        L.append(f"- Evaluator build: outcome {ev.get('outcome')}, reward {inf.get('reward')} after {inf.get('turns')} "
                 f"tool calls; reward per grade call: {inf.get('grade_history')}")
        if ev.get('probe'):
            L.append(f"- Blind probe: reward {ev['probe']['reward']}")
    if check and check.get('rounds'):
        L.append('- Rounds: ' + ', '.join(f"r{h['round']} {'ready' if h['pass'] else 'not ready'}"
                                         for h in check['rounds']))
    L += ['', '## Targeted limitation', f"`{lim.get('id')}` ({lim.get('confidence')} confidence): {lim.get('name')}", '',
          f"- Mechanism: {lim.get('mechanism')}",
          f"- Requirements that should catch it: {', '.join(draft['catching_rows'])}",
          f"- Why it survives the solver's own checks: {draft['mechanism_survival']}",
          f"- Where the assessment says it bites: {a.get('limitation_bites', '-')}", '']
    if a:
        L += ['## What the build showed', *[f'- {x}' for x in a.get('reasons', [])], '', '## Binding checks',
              *[f'- {x}' for x in a.get('binding_checks', [])], '', '## For the SME',
              *[f'- {x}' for x in a.get('sme_notes', [])], '']
    if inf.get('checks'):
        L += ['## Final grader output of the evaluator build', '```', inf['checks'], '```', '']
    kit = (ev or {}).get('kit') or {}
    if kit:
        L += ['## Grader coverage (brief requirement -> kforge requirements)',
              *[f'- {c}' for c in kit.get('coverage', [])], *([f"- Kit notes: {kit['notes']}"] if kit.get('notes') else []), '']
    fixes = (ev or {}).get('fixes') or (check or {}).get('top_fixes') or []
    if fixes and not ready:
        L += ['## Fixes still open', *[f'- {f}' for f in fixes], '']
    L += ['## Public designs checked', *[f"- {x['name']} ({x['source']}): fails {x['fails']}" for x in draft['public_designs']],
          '', '## Open risks (author)', *[f'- {r}' for r in draft['open_risks']], '']
    return canary_md('\n'.join(L))


def package(draft_dir, out_dir):
    meta = json.loads((draft_dir / 'draft.json').read_text())
    draft = meta['draft']
    domain = Domain(meta.get('domain', 'electrical'))
    load = lambda p: json.loads(p.read_text()) if p.exists() else None
    check, ev = load(draft_dir / 'skill_check.json'), load(draft_dir / 'evaluation.json')
    kit_dir = draft_dir / 'kit'
    from evidence import physically_ready, draft_digest
    meta['ready'] = bool(meta.get('ready') and physically_ready(ev) and ev.get('draft_digest') == draft_digest(draft))
    kit_ok = bool(ev and ev.get('draft_digest') == draft_digest(draft) and (ev.get('kit') or {}).get('ok') and (kit_dir / 'tests' / 'requirements.yaml').exists())
    root = out_dir / draft['slug']
    if root.exists():
        shutil.rmtree(root)
    for sub in ('environment', 'handbook', 'solution', 'tests', 'sme'):
        (root / sub).mkdir(parents=True)
    lim = meta.get('limitation') or {}

    (root / 'instruction.md').write_text(canary_md(draft['instruction_md']))
    (root / 'task.toml').write_text(TASK_TOML.format(
        canary=CANARY, name=toml_str(f"fair-forge/{draft['slug']}"), description=toml_str(draft['one_line']),
        keywords=json.dumps([domain.name, meta.get('subdomain', ''), lim.get('id', '')]),
        subcategory=toml_str(meta.get('subdomain', '')), limitation=toml_str(lim.get('id', '')),
        difficulty=toml_str(draft['difficulty_target']), difficulty_reason=toml_str(draft['difficulty_reason']),
        reference=toml_str(draft['reference_outline']),
        grader=toml_str('kforge grade on the delivered KiCad project: ' + '; '.join(
            f"{c['cid']} {c.get('primitive', '')}: {c['method']}" for c in draft['grader_checks'])),
        astra=toml_str(f"{check['astra']['p_pass_per_attempt']}" if check else 'n/a')))
    (root / 'README.md').write_text(README.format(
        title=draft['title'], canary=CANARY, one_line=draft['one_line'], date=time.strftime('%Y-%m-%d'),
        limitation=lim.get('id', '-'), status='Ready draft: real kforge grader, evaluator build passed; golden '
        'solution to be written by the SME.' if meta.get('ready') else 'Not ready: see SME_NOTES.md.'))

    env = root / 'environment'
    (env / 'Dockerfile').write_text(ENV_DOCKERFILE.format(canary=CANARY, image=domain['images']['registry']))
    if (kit_dir / 'starter').exists():
        shutil.copytree(kit_dir / 'starter', env / 'starter')
    else:
        (env / 'starter' / 'design').mkdir(parents=True)
    if (kit_dir / 'input_assets').exists():
        shutil.copytree(kit_dir / 'input_assets', env / 'input_assets')
    else:
        (env / 'input_assets').mkdir()
    (env / 'input_assets' / '.keep').write_text(CANARY + '\n')

    (root / 'handbook' / 'handbook.md').write_text(canary_md(draft['handbook_md']))
    if draft['parts_catalogue_md'].strip():
        (root / 'handbook' / 'parts_catalogue.md').write_text(canary_md(draft['parts_catalogue_md']))

    tests = root / 'tests'
    if kit_ok:
        shutil.copytree(kit_dir / 'tests', tests, dirs_exist_ok=True)
        req = tests / 'requirements.yaml'
        req.write_text(canary_yaml(req.read_text()))
        (tests / 'test.sh').write_text(TEST_SH.format(canary=CANARY))
        (tests / 'Dockerfile').write_text(TESTS_DOCKERFILE.format(canary=CANARY, image=domain['images']['registry']))
        shutil.copytree(REPO / domain['kforge'], tests / 'kforge', ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
    else:
        (tests / 'test.sh').write_text(SMOKE_SH.format(canary=CANARY))
        (tests / 'Dockerfile').write_text(f"# {CANARY}\nFROM {domain['images']['registry']}\nCOPY . /tests/\n")
    (tests / 'test.sh').chmod(0o755)

    (root / 'solution' / 'REFERENCE_OUTLINE.md').write_text(canary_md(
        f"# Reference outline (evaluator-only)\n\n{draft['reference_outline']}"))
    (root / 'solution' / 'solve.sh').write_text(
        f'#!/usr/bin/env bash\n# {CANARY}\necho "golden solution not written yet: see SME_NOTES.md" >&2\nexit 1\n')
    (root / 'solution' / 'solve.sh').chmod(0o755)

    design = draft_dir / 'eval' / 'informed' / 'design'
    if design.exists():
        shutil.copytree(design, root / 'sme' / 'evaluator_design')
    for name in ('evaluation.json', 'skill_check.json'):
        if (draft_dir / name).exists():
            shutil.copy(draft_dir / name, root / 'sme' / name)
    (root / 'SME_NOTES.md').write_text(sme_notes(meta, check, ev))
    archive = shutil.make_archive(str(root), 'zip', root_dir=out_dir, base_dir=draft['slug'])
    print(f"  packaged {Path(archive).name}{' (ready)' if meta.get('ready') else ''}", flush=True)
    return Path(archive)
